#suma y resta (+ -)
suma = 5 + 3
print(suma)

resta = 5 - 3
print(resta)


#multiplicación y división (* /)
multiplicacion = 5 * 3
print(multiplicacion)

division = 5 / 3
print(division)

#módulo (%)
modulo = 5 % 3
print(modulo)

#exponenciación (**)
exponenciacion = 5 ** 3
print(exponenciacion)

#división entera (//) devuelve entero redondeado hacia bajo
division_entera = 5 // 3 
print(division_entera)


